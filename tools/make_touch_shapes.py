"""Touch control artwork -> mgs_native/touch_shapes.h (the outlines touchcontrols.cpp draws).

    python tools/make_touch_shapes.py [controlsExample.ai] [mgs_native/touch_shapes.h]

The .ai (a PDF inside) holds stroked outlines, one stroke colour per control: green = the D-pad (outer frame,
the centre button = the second-largest rounded square, its inner square, four direction marks), purple = the
left soft key, red = the right soft key, black = the A button (ring + inner square), light green = the B
button (first-person view, a triangle). The colours only tell the controls apart: all are drawn in one colour. Curves are flattened to
polylines; each control's points are relative to the top-left of its own bounding box, in artwork points, and
its stroke width is kept. The relative placement of the controls in the artwork is written too (default
layout). Needs PyMuPDF.
"""
import os
import sys

import fitz

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTROLS = {   # stroke colour (rounded 0..255) -> control
    (16, 149, 103): 'dpad', (42, 40, 117): 'lsk', (213, 30, 70): 'rsk', (10, 12, 23): 'a',
    (124, 194, 66): 'b',
}
SEGMENTS = 12   # per cubic curve at most; about one per artwork point of its length
MIN_STEP = 0.2  # artwork points: closer points are dropped (tiny segments make spikes at thick-line joins)


def flatten(items):
    pts = []
    for it in items:
        kind = it[0]
        if kind == 'l':
            p0, p1 = it[1], it[2]
            if not pts:
                pts.append((p0.x, p0.y))
            pts.append((p1.x, p1.y))
        elif kind == 'c':
            p0, c1, c2, p1 = it[1], it[2], it[3], it[4]
            if not pts:
                pts.append((p0.x, p0.y))
            length = sum(((b.x - a.x) ** 2 + (b.y - a.y) ** 2) ** 0.5 for a, b in ((p0, c1), (c1, c2), (c2, p1)))
            n = max(1, min(SEGMENTS, round(length)))
            for i in range(1, n + 1):
                t = i / n
                u = 1 - t
                pts.append((u * u * u * p0.x + 3 * u * u * t * c1.x + 3 * u * t * t * c2.x + t * t * t * p1.x,
                            u * u * u * p0.y + 3 * u * u * t * c1.y + 3 * u * t * t * c2.y + t * t * t * p1.y))
        elif kind == 're':
            r = it[1]
            pts += [(r.x0, r.y0), (r.x1, r.y0), (r.x1, r.y1), (r.x0, r.y1)]
    dedup = []
    for i, p in enumerate(pts):
        if not dedup or i == len(pts) - 1 or abs(p[0] - dedup[-1][0]) + abs(p[1] - dedup[-1][1]) > MIN_STEP:
            dedup.append(p)
    closed = len(dedup) > 2 and abs(dedup[0][0] - dedup[-1][0]) + abs(dedup[0][1] - dedup[-1][1]) < 0.05
    if closed:
        dedup.pop()
    if len(dedup) > 2 and abs(dedup[-1][0] - dedup[-2][0]) + abs(dedup[-1][1] - dedup[-2][1]) <= MIN_STEP:
        dedup.pop(-2)   # the kept end point came too close to the one before it
    return dedup, closed


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'controlsExample.ai')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, 'mgs_native', 'touch_shapes.h')
    page = fitz.open(src)[0]
    groups = {}
    for d in page.get_drawings():
        col = tuple(round(c * 255) for c in (d.get('color') or (0, 0, 0)))
        name = min(CONTROLS.items(), key=lambda kv: sum(abs(a - b) for a, b in zip(kv[0], col)))[1]
        pts, closed = flatten(d['items'])
        groups.setdefault(name, []).append({'pts': pts, 'closed': closed, 'width': d.get('width') or 1.0, 'rect': d['rect']})

    lines = ['// Generated by tools/make_touch_shapes.py from the touch control artwork. Do not edit.',
             '#pragma once', '', 'namespace TouchShapes {', '',
             'struct Path { const float* xy; int count; bool closed; float width; int role; };',
             '// role: 0 outline, 1 the D-pad centre button, 2 direction mark (up, right, down, left = 2..5)',
             'struct Shape { const Path* paths; int count; float w, h, x, y; };   // size, artwork position', '']
    order = ['dpad', 'a', 'lsk', 'rsk', 'b']   # = TouchControls::Control
    for name in order:
        g = groups[name]
        x0 = min(p['rect'].x0 for p in g); y0 = min(p['rect'].y0 for p in g)
        x1 = max(p['rect'].x1 for p in g); y1 = max(p['rect'].y1 for p in g)
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        closed_by_area = sorted((p for p in g if p['closed']), key=lambda p: -p['rect'].width * p['rect'].height)
        centre = closed_by_area[1] if name == 'dpad' and len(closed_by_area) > 1 else None
        paths = []
        for i, p in enumerate(g):
            role = 0
            if p is centre:
                role = 1
            elif name == 'dpad' and not p['closed']:   # a direction mark: which side of the centre it's on
                mx, my = (p['rect'].x0 + p['rect'].x1) / 2 - cx, (p['rect'].y0 + p['rect'].y1) / 2 - cy
                role = 2 + ((0 if my < 0 else 2) if abs(my) > abs(mx) else (1 if mx > 0 else 3))
            arr = '%s_%d' % (name, i)
            xy = ', '.join('%.2ff, %.2ff' % (x - x0, y - y0) for x, y in p['pts'])
            lines.append('static const float %s[] = { %s };' % (arr, xy))
            paths.append('{ %s, %d, %s, %.2ff, %d }' % (arr, len(p['pts']), 'true' if p['closed'] else 'false', p['width'], role))
        lines.append('static const Path %s_paths[] = {\n    %s };' % (name, ',\n    '.join(paths)))
        lines.append('static const Shape %s = { %s_paths, %d, %.2ff, %.2ff, %.2ff, %.2ff };' % (name, name, len(paths), x1 - x0, y1 - y0, x0, y0))
        lines.append('')
    lines.append('} // namespace TouchShapes')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('Wrote %s (%s)' % (out, ', '.join('%s: %d paths' % (n, len(groups[n])) for n in order)))


if __name__ == '__main__':
    main()
